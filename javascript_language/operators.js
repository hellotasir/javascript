// Assignment, Comparison or Logical, Addition and Multiplication Operators in JavaScript

let a = 10;
let b = 5;

// Assignment Operator
let c = a;
console.log('Value of c (after assignment from a): ' + c);

// Comparison Operators
console.log('Is a equal to b? ' + (a == b)); // false
console.log('Is a not equal to b? ' + (a != b)); // true
console.log('Is a greater than b? ' + (a > b)); // true
console.log('Is a less than or equal to b? ' + (a <= b)); // false

// Addition Operator
let sum = a + b;
console.log('Sum of a and b: ' + sum);

// Multiplication Operator
let product = a * b;
console.log('Product of a and b: ' + product);

let text1 = "What a very ";
text1 += "nice day";
console.log(text1);

let x = 5 + 5;
let y = "5" + 5;
let z = "Hello" + 5;
console.log(x);
console.log(y);
console.log(z);